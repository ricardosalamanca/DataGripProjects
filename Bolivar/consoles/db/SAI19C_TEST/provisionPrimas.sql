  AND ((PLZAS.POL_SUC_CIA_CDGO = SCRSL.SUC_CIA_CDGO)
    AND (PLZAS.POL_SUC_CDGO = SCRSL.SUC_CDGO)
    AND (PLZAS.POL_TPOPLZA = 'C')
    AND (CRTFCDOS.CER_RAM_CDGO = PLZAS.POL_RAM_CDGO)
    AND (CRTFCDOS.CER_CLSE_PLZA = PLZAS.POL_CDGO_CLSE)
    AND (CRTFCDOS.CER_NMRO_PLZA = PLZAS.POL_NMRO_PLZA)
    AND (ESTADO_CTA_RCBOS.EST_SLCTUD(+) = CRTFCDOS.CER_NMRO_CRTFCDO)
    AND (ESTADO_CTA_RCBOS.EST_PLZA(+) = CRTFCDOS.CER_NMRO_PLZA)
