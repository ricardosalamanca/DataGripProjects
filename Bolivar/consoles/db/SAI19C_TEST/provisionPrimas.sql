FROM CRTFCDOS, PLZAS
WHERE CER_VLOR_SLDO > 2
  AND CER_FCHA_PRDCCION >= to_date('01/01/1900', 'dd/mm/yyyy')
  AND CER_FCHA_PRDCCION <= to_date('30/04/2025', 'dd/mm/yyyy')
  AND POL_TPOPLZA = 'C'
  AND CER_ESTDO_PRDCCION NOT IN ('00','70','80', '50')
  AND CER_RAM_CDGO = POL_RAM_CDGO
  AND CER_CLSE_PLZA = POL_CDGO_CLSE
  AND CER_NMRO_PLZA = POL_NMRO_PLZA
  AND CER_FCHA_PRDCCION < to_date('30/04/2025', 'dd/mm/yyyy') - 75
  AND CRTFCDOS.CER_NMRO_PLZA = 1143
