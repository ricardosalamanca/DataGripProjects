         SCRSL.SUC_CDGO,
         PLZAS.POL_NMRO_PLZA,
         CRTFCDOS.CER_NMRO_CRTFCDO,
         CRTFCDOS.CER_FCHA_DSDE_ACTUAL
ORDER BY DIFERENCIA DESC;

