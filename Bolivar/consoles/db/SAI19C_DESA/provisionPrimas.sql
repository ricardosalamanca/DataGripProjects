FROM PLZAS,
     CRTFCDOS,
     SCRSL,
     ESTADO_CTA_RCBOS,
     CRTFCDO_ANLDO,
     CG_REF_CODES
WHERE (CRTFCDOS.CER_VLOR_SLDO > 2
    AND CRTFCDOS.CER_NMRO_PLZA = 1143
