   COUNT(*)
FROM PRVSION_PRMAS PP
         INNER JOIN PLZAS P
                    ON PP.PRO_NMRO_PLZA = P.POL_NMRO_PLZA
                        AND PP.PRO_CLSE_PLZA = P.POL_CDGO_CLSE
                        AND PP.PRO_RAM_CDGO = P.POL_RAM_CDGO
